from t64a import *
import os
r = open(os.environ.get("FROM", SC + "/build/p64.gbc"), "rb").read()
fc = r[0xD1F3:0xD1F9]
def zeros(b, k, rod, n=50):
    # c2de = count of d==0 over n calls
    asm = bytes([0xAF, 0xEA, 0xDE, 0xC2, 0x3E, n, 0xEA, 0xDF, 0xC2])
    asm += bytes([0x3E, k[0], 0xEA, 0x7B, 0xDC, 0x3E, k[1], 0xEA, 0x7C, 0xDC])
    loop = bytes([0x16, 0x01, 0x1E, rod]) + fc + bytes([0x7A, 0xA7, 0x20, 0x07, 0xFA, 0xDE, 0xC2, 0x3C, 0xEA, 0xDE, 0xC2,
                  0xFA, 0xDF, 0xC2, 0x3D, 0xEA, 0xDF, 0xC2])
    asm += loop + bytes([0x20, (-(len(loop) + 2)) & 0xFF])
    asm += bytes([0x3E, 24, 0xEA, 0x7B, 0xDC, 0x3E, 4, 0xEA, 0x7C, 0xDC, 0xC9])
    for i, v in enumerate(asm): b.g.cmd('rpoke %x %d' % (SOFF + 0x40 + i, v))
    b.script([0x0E, SB, (SA + 0x40) & 0xFF, (SA + 0x40) >> 8], 120)
    b.bank1(); return b.peek(0xC2DE, 2)
b = Bot(state='p64nb.st', out=OUT+'/fish2')
for k in ((17,1),(26,88),(10,1)):
    for rod in (0,1,2): print(k, rod, zeros(b,k,rod), flush=True)
